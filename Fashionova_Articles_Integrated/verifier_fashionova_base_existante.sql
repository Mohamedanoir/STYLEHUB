-- Controle en lecture seule de la base deja utilisee par Fashionova.
-- Connectez-vous au schema FASHIONNOVA puis executez le script.
-- Ce script ne cree, ne modifie et ne supprime aucun objet ni aucune donnee.

WITH objets_attendus (type_objet, nom_objet) AS (
    SELECT 'TABLE', 'ARTICLES' FROM DUAL UNION ALL
    SELECT 'TABLE', 'CLIENTS' FROM DUAL UNION ALL
    SELECT 'TABLE', 'COMMANDES' FROM DUAL UNION ALL
    SELECT 'TABLE', 'CONTENIR' FROM DUAL UNION ALL
    SELECT 'TABLE', 'EMPLOYES' FROM DUAL UNION ALL
    SELECT 'TABLE', 'LOG_ACTIVITE' FROM DUAL UNION ALL
    SELECT 'TABLE', 'MACHINES' FROM DUAL UNION ALL
    SELECT 'TABLE', 'MAQUETTES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_ARTICLES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_CLIENTS' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_COMMANDES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_EMPLOYES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_LOG' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_MACHINES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'SEQ_MAQUETTES' FROM DUAL UNION ALL
    SELECT 'SEQUENCE', 'FASHIONOVA_CLIENT_SEQ' FROM DUAL
), objets_existants AS (
    SELECT 'TABLE' type_objet, TABLE_NAME nom_objet FROM USER_TABLES
    UNION ALL
    SELECT 'SEQUENCE', SEQUENCE_NAME FROM USER_SEQUENCES
)
SELECT a.type_objet,
       a.nom_objet,
       CASE WHEN e.nom_objet IS NULL THEN 'MANQUANT' ELSE 'PRESENT' END AS etat
  FROM objets_attendus a
  LEFT JOIN objets_existants e
    ON e.type_objet = a.type_objet
   AND e.nom_objet = a.nom_objet
 ORDER BY a.type_objet, a.nom_objet;

-- Colonnes utilisees par les CRUD integres.
WITH colonnes_attendues (table_name, column_name) AS (
    SELECT 'ARTICLES', 'ID_ARTICLE' FROM DUAL UNION ALL
    SELECT 'ARTICLES', 'NOM_ARTICLE' FROM DUAL UNION ALL
    SELECT 'ARTICLES', 'ID_MAQUETTE' FROM DUAL UNION ALL
    SELECT 'ARTICLES', 'ID_MACHINE' FROM DUAL UNION ALL
    SELECT 'CLIENTS', 'ID_CLIENT' FROM DUAL UNION ALL
    SELECT 'CLIENTS', 'ID_APP' FROM DUAL UNION ALL
    SELECT 'CLIENTS', 'PRENOM_CLIENT' FROM DUAL UNION ALL
    SELECT 'EMPLOYES', 'ID_EMPLOYE' FROM DUAL UNION ALL
    SELECT 'EMPLOYES', 'MOT_DE_PASSE' FROM DUAL UNION ALL
    SELECT 'COMMANDES', 'ID_COMMANDE' FROM DUAL UNION ALL
    SELECT 'COMMANDES', 'ID_CLIENT' FROM DUAL UNION ALL
    SELECT 'MAQUETTES', 'ID_MAQUETTE' FROM DUAL UNION ALL
    SELECT 'MAQUETTES', 'ID_EMPLOYE' FROM DUAL UNION ALL
    SELECT 'MACHINES', 'ID_MACHINE' FROM DUAL
)
SELECT a.table_name,
       a.column_name,
       CASE WHEN c.column_name IS NULL THEN 'MANQUANTE' ELSE 'PRESENTE' END AS etat
  FROM colonnes_attendues a
  LEFT JOIN USER_TAB_COLUMNS c
    ON c.table_name = a.table_name
   AND c.column_name = a.column_name
 ORDER BY a.table_name, a.column_name;
